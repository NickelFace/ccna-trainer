#!/usr/bin/env bash
# Остановка офлайн-тренажёра CCNA 200-301 (порт 8099).
# Обычный способ — Ctrl+C в терминале с run.sh; этот скрипт нужен,
# когда терминал закрыт, а процесс остался висеть на порту.
PORT=8099
PIDS=$(lsof -t -i :$PORT 2>/dev/null)
if [ -z "$PIDS" ]; then
  echo "Порт $PORT свободен — останавливать нечего."
  exit 0
fi
kill $PIDS && echo "Остановлен процесс на порту $PORT (PID: $PIDS)"
